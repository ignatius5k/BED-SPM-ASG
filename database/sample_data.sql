-- ---------------------------------------------------------
-- SA2-48 sample-data verification queries
-- Expected popular item: Steamed Chicken Rice, 7 sold, $38.50 revenue.
-- Expected peak hour: 12:00, 5 orders, $39.00 sales.
-- The cancelled 14:00 order must not appear in either result.
-- ---------------------------------------------------------
SELECT TOP 5
  mi.ItemName,
  SUM(oi.Quantity) AS QuantitySold,
  CAST(SUM(oi.Quantity * oi.UnitPrice) AS DECIMAL(10, 2)) AS Revenue
FROM OrderItems oi
INNER JOIN Orders o ON oi.OrderID = o.OrderID
INNER JOIN MenuItems mi ON oi.MenuItemID = mi.MenuItemID
WHERE o.Status IN ('paid', 'completed')
GROUP BY mi.MenuItemID, mi.ItemName
ORDER BY QuantitySold DESC, Revenue DESC, mi.ItemName;

SELECT
  DATEPART(HOUR, OrderDate) AS HourOfDay,
  COUNT(OrderID) AS TotalOrders,
  CAST(SUM(TotalAmount) AS DECIMAL(10, 2)) AS TotalSales
FROM Orders
WHERE Status IN ('paid', 'completed')
GROUP BY DATEPART(HOUR, OrderDate)
ORDER BY TotalOrders DESC, HourOfDay;
